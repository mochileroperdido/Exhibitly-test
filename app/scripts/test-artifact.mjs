import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
mkdirSync('scripts/.shots', { recursive: true });
const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
const page = await browser.newPage({ viewport: { width: 1194, height: 834 }, deviceScaleFactor: 2 });
page.on('pageerror', (e) => console.log('EXC:', e.message));
await page.goto('file:///home/user/Exhibitly-test/app/dist/exhibly-artifact.html');
await page.waitForSelector('model-viewer');
const t0 = Date.now();
await page.waitForFunction(() => document.querySelector('model-viewer')?.loaded, { timeout: 30000 });
console.log('model loaded in', Date.now() - t0, 'ms (from inlined data URI)');
await page.waitForTimeout(1200);
await page.screenshot({ path: 'scripts/.shots/artifact-1-attract.png' });
await page.click('model-viewer', { position: { x: 597, y: 417 } });
await page.waitForTimeout(700);
console.log('hotspots:', await page.locator('button[slot^="hotspot-"]').count());
await page.screenshot({ path: 'scripts/.shots/artifact-2-explore.png' });
await browser.close();
console.log('OK');
